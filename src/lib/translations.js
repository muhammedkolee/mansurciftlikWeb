// t() helper: resolves { tr, en } objects or plain strings
export function t(obj, lang = 'tr') {
  if (!obj) return '';
  if (typeof obj === 'string') return obj;
  if (typeof obj === 'number') return String(obj);
  return obj[lang] ?? obj.tr ?? '';
}
